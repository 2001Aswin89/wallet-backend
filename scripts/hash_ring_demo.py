"""Stretch milestone demo: key distribution and how many keys move when a shard is added.

    python -m scripts.hash_ring_demo          # writes docs/sharding-demo.md
"""
from collections import Counter
from pathlib import Path

from sharding.hash_ring import HashRing

OUT = Path(__file__).resolve().parent.parent / "docs" / "sharding-demo.md"
KEYS = range(1, 100_001)               # 100,000 user ids


def spread(assign: dict[int, str]) -> str:
    c = Counter(assign.values())
    return "\n".join(f"| {n} | {c[n]:,} | {c[n] / len(assign) * 100:.1f}% |" for n in sorted(c))


def main() -> None:
    shards = [f"shard-{i}" for i in range(1, 5)]
    out = ["# Consistent hashing demo", "",
           f"{len(KEYS):,} user ids routed over 4 shards, then a 5th shard added. "
           "Generated by `python -m scripts.hash_ring_demo`.", ""]
    for vnodes in (1, 10, 100, 400):
        ring = HashRing(shards, vnodes=vnodes)
        counts = Counter(ring.get_node(k) for k in KEYS)
        ideal = len(KEYS) / len(shards)
        worst = max(abs(c - ideal) for c in counts.values()) / ideal * 100
        out.append(f"- **{vnodes} virtual node(s) per shard:** busiest/least-busy shard is within "
                   f"{worst:.1f}% of the ideal {int(ideal):,} keys ({', '.join(f'{counts[s]:,}' for s in shards)}).")
    ring = HashRing(shards, vnodes=100)
    before = {k: ring.get_node(k) for k in KEYS}
    out += ["", "## Distribution with 100 virtual nodes per shard", "", "| shard | users | share |", "|---|---|---|",
            spread(before), ""]

    ring.add_node("shard-5")
    after = {k: ring.get_node(k) for k in KEYS}
    moved = sum(1 for k in KEYS if before[k] != after[k])
    only_to_new = all(after[k] == "shard-5" for k in KEYS if before[k] != after[k])
    mod_before = {k: f"shard-{k % 4 + 1}" for k in KEYS}
    mod_after = {k: f"shard-{k % 5 + 1}" for k in KEYS}
    mod_moved = sum(1 for k in KEYS if mod_before[k] != mod_after[k])
    out += [
        "## Adding a 5th shard", "",
        "| routing | keys that change shard | share of all keys |", "|---|---|---|",
        f"| consistent hash ring (100 vnodes) | {moved:,} | {moved / len(KEYS) * 100:.1f}% |",
        f"| `user_id % N` (N from 4 to 5) | {mod_moved:,} | {mod_moved / len(KEYS) * 100:.1f}% |", "",
        f"Ideal for 4 to 5 shards is 1/5 = 20.0%. Every key that moved on the ring moved to the new shard "
        f"(none shuffled between old shards): **{only_to_new}**.", "",
        "## Distribution after the 5th shard", "", "| shard | users | share |", "|---|---|---|", spread(after), "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
